/**
 * Generates `content/docs/references/codes.mdx` from the code registry
 * (`omni diagnostics list --format md`). Run with `bun run gen:codes`.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const table = Bun.spawnSync(["omni", "diagnostics", "list", "--format", "md"], {
    stdout: "pipe",
    stderr: "inherit",
});
if (table.exitCode !== 0) {
    throw new Error("`omni diagnostics list` failed");
}

const page = `---
title: "Error and notice codes"
description: "Every error and notice code omni can report"
---

Every message omni reports about a run or a failure has a code. Look one up with
\`omni explain <code>\` (or the \`explain\` MCP tool, or the
\`omni://codes/<code>\` resource).

- **error** codes belong to a returned failure: the operation stopped.
- **notice** codes belong to a message about a run that still completed. Its
  level is \`info\`, \`warn\` or \`error\` and never changes the exit status.
- **Essential** notices are never hidden by \`-q\` and are always delivered over
  MCP.
- **Stable** codes are a contract: they are never renamed or reused. Unstable
  codes may change before release.

This page is generated by \`bun run gen:codes\`.

${table.stdout.toString()}`;

writeFileSync(
    join(import.meta.dirname, "..", "content/docs/references/codes.mdx"),
    page,
);
